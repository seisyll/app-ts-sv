/* ―― » Palette generator ( from billing-app ) — `bun run generate:palettes`.

        Reads PALETTES and RADII from src/lib/appearance.ts, fetches each recipe's colours
        from shadcn-svelte's registry, merges them the way upstream's buildRegistryTheme
        does ( the base colour's full set, the accent's on top ) and writes
        src/lib/styles/palettes.css. Run on a developer's machine when the catalog changes;
        the output is committed and reviewed like any source file.

        Enforced, not hoped for:
        - COLOUR VARIABLES ONLY: anything else the registry ships ( radius ) is dropped, and
          a key nobody has decided about fails the run.
        - COMPLETE PAIRS: a palette's light and dark blocks define the same variables.
          `html.palette-x` outranks `.dark`, so a variable set only for light would leak
          into dark mode; `html.dark.palette-x` shadows it, but only if it is there. */

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { PALETTES, RADII } from '../src/lib/appearance'

const REGISTRY = 'https://shadcn-svelte.com/registry/colors'

const COLOR_KEYS = new Set( [
	'background', 'foreground', 'card', 'card-foreground', 'popover', 'popover-foreground',
	'primary', 'primary-foreground', 'secondary', 'secondary-foreground', 'muted', 'muted-foreground',
	'accent', 'accent-foreground', 'destructive', 'border', 'input', 'ring',
	'chart-1', 'chart-2', 'chart-3', 'chart-4', 'chart-5',
	'sidebar', 'sidebar-foreground', 'sidebar-primary', 'sidebar-primary-foreground',
	'sidebar-accent', 'sidebar-accent-foreground', 'sidebar-border', 'sidebar-ring'
] )
const DROPPED_KEYS = [ 'radius' ]

type RegistryTheme = { cssVars : { light : Record<string, string>, dark : Record<string, string> } }

const cache = new Map<string, RegistryTheme>()

async function registry( name : string ) : Promise<RegistryTheme> {
	if ( !cache.has( name ) ) {
		const response = await fetch( `${ REGISTRY }/${ name }.json` )

		if ( !response.ok )
			throw new Error( `the registry has no colour '${ name }' ( HTTP ${ response.status } )` )

		cache.set( name, await response.json() as RegistryTheme )
	}

	return cache.get( name )!
}

function merged( base : Record<string, string>, accent : Record<string, string> ) : Record<string, string> {
	const vars = { ...base, ...accent }

	for ( const key of DROPPED_KEYS )
		delete vars[ key ]

	const unknown = Object.keys( vars ).filter( ( key ) => !COLOR_KEYS.has( key ) )

	if ( unknown.length > 0 )
		throw new Error( `the registry ships keys outside the colour allow-list: ${ unknown.join( ', ' ) }. Decide each, then extend COLOR_KEYS or DROPPED_KEYS.` )

	return vars
}

const block = ( selector : string, vars : Record<string, string> ) =>
	`${ selector } {\n${ Object.entries( vars ).map( ( [ key, value ] ) => `\t--${ key }: ${ value };` ).join( '\n' ) }\n}`

const blocks : string[] = []

for ( const palette of PALETTES ) {
	const base = await registry( palette.base )
	const accent = await registry( palette.accent )
	const light = merged( base.cssVars.light, accent.cssVars.light )
	const dark = merged( base.cssVars.dark, accent.cssVars.dark )

	if ( Object.keys( light ).sort().join() !== Object.keys( dark ).sort().join() )
		throw new Error( `palette '${ palette.id }': its light and dark blocks define different variables` )

	blocks.push( `/* ${ palette.id } — ${ palette.base } ← ${ palette.accent } */`, block( `html.palette-${ palette.id }`, light ), block( `html.dark.palette-${ palette.id }`, dark ) )
}

blocks.push( '/* radius — one variable, mode-independent */', ...RADII.map( ( radius ) => `html.radius-${ radius.id } {\n\t--radius: ${ radius.value };\n}` ) )

const header = `/* GENERATED by scripts/generate-palettes.ts — do not edit. Regenerate with
   \`bun run generate:palettes\` after changing PALETTES or RADII in src/lib/appearance.ts.
   The html-prefixed selectors outrank app.css's :root and compose with mode-watcher's
   .dark whatever the stylesheet order. */
`

writeFileSync( join( import.meta.dir, '..', 'src', 'lib', 'styles', 'palettes.css' ), `${ header }\n${ blocks.join( '\n\n' ) }\n` )

console.log( `✓ ${ PALETTES.length } palettes, ${ RADII.length } radii → src/lib/styles/palettes.css` )
